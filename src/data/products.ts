function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

function buildVariants(def: Def, index: number): Variant[] {
  const colors = (def.colors ?? []).map((c) => COLORS[c].name)
  const sizes = def.sizes ?? []
  const colorList = colors.length ? colors : [undefined]
  const sizeList = sizes.length ? sizes : [undefined]
  const variants: Variant[] = []
  let n = 0
  for (const color of colorList) {
    for (const size of sizeList) {
      const keys = [color && size ? `${color}/${size}` : undefined, color, size].filter(Boolean) as string[]
      const override = keys.map((k) => def.stock?.[k]).find((v) => v !== undefined)
      // Deterministic "random" stock between 6 and 24.
      const stock = override ?? 6 + ((index * 7 + n * 5) % 19)
      variants.push({
        sku: `${def.id}-${slugify([color, size].filter(Boolean).join('-') || 'std')}`,
        color,
        size,
        stock,
      })
      n++
    }
  }
  return variants
}

